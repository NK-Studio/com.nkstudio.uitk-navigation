namespace NKStudio.UITKNavigation.Animation
{
    /// <summary>
    /// Defines the available Visibility State values.
    /// </summary>
    internal enum VisibilityState
    {
        /// <summary>
        /// Represents the visible option.
        /// </summary>
        Visible,

        /// <summary>
        /// Represents the not visible option.
        /// </summary>
        NotVisible,

        /// <summary>
        /// Represents the showing option.
        /// </summary>
        Showing,

        /// <summary>
        /// Provides supporting functionality for this member.
        /// </summary>
        Hiding
    }
}
