namespace NKStudio.UITKNavigation.Elements
{
    /// <summary>
    /// Defines the available UI View Start Behaviour values.
    /// </summary>
    internal enum UIViewStartBehaviour
    {
        /// <summary>
        /// Represents the disabled option.
        /// </summary>
        Disabled,

        /// <summary>
        /// Represents the instant hide option.
        /// </summary>
        InstantHide,

        /// <summary>
        /// Represents the instant show option.
        /// </summary>
        InstantShow,

        /// <summary>
        /// Represents the animation hide option.
        /// </summary>
        AnimationHide,

        /// <summary>
        /// Provides supporting functionality for this member.
        /// </summary>
        AnimationShow
    }
}
